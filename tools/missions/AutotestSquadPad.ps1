# AutotestSquadPad: the control pad works the squadmate messaging menu (#119). Run with -at_time 40.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestSquadPad' 'Autotest squad pad' @'
Generated by tools/missions/AutotestSquadPad.ps1; edit that, not this file.
autotest: squad pad
Autotest test of the squadmate messaging menu worked by the control pad (#119): a script in PadGame.cpp gives the pad
output at fixed mission times and checks the menu after each step: open, Wings, Beta, Form on my wing; open, back,
close; open, All fighters, back, close; South held for push-to-talk. Beta flies against a few weak Kappa ships meanwhile.
Run with -at_time 40.
'@

Add-Player $m
foreach ($n in 1..3) {
	[void](Add-Ship $m @{ Name = "Beta $n"; Class = 'GTF Myrmidon'; Loc = @((-300 + 120 * $n), 0, 200); Vel = 30
		Goals = '( ai-chase-wing "Kappa" 89 )' })
}
Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2', 'Beta 3'); Hotkey = 1 }
foreach ($n in 1..3) {
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Mara'; Team = 'Hostile'; Loc = @((-300 + 150 * $n), 50, 1500); Face = 'back'; Vel = 30; Hull = 20
		Goals = '( ai-chase-wing "Beta" 89 )'; Primary = @('Shivan Light Laser') })
}
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3'); Waves = 2; Threshold = 0 }

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Goal $m 'Primary' 'Kappa' 'Destroy Kappa' '( is-destroyed-delay 0 "Kappa" )'
Add-Message $m 'Start' 'Autotest squad pad. Beta, stand by for orders.'

Save-Mission $m
