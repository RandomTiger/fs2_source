# AutotestTraining: training messages, which are queued, voiced and timed by the training message code
# (MissionTraining.cpp). Run with -at_time 90.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestTraining' 'Autotest training messages' @'
Generated by tools/missions/AutotestTraining.ps1; edit that, not this file.
Autotest test of training messages. The training message queue only runs while a ship named
"instructor" is present. Messages with a voice, one without, a delayed one with a set duration, and two
queued at once. No key tokens in the text: an unbound key opens a popup that stops the run.
Run with -at_time 90.
'@

Add-Player $m
[void](Add-Ship $m @{ Name = 'instructor'; Class = 'GTF Ulysses'; Loc = @(0, 0, 150); Face = 'back'; Flags = @('protect-ship') })

Add-Event $m @{ Name = 'Welcome'; Formula = "( when`n   ( true )`n   ( training-msg `"Welcome`" )`n)" }
Add-Step $m 'Voiced' 10 @('( training-msg "Voiced" )')
Add-Step $m 'Silent' 10 @('( training-msg "Silent" )')
Add-Step $m 'Delayed' 10 @('( training-msg "Delayed" "Delayed" 3 6 )')
Add-Step $m 'Two at once' 15 @('( training-msg "First of two" )', '( training-msg "Second of two" )')
Add-Step $m 'Done' 20 @('( training-msg "Done" )')

Add-Message $m 'Welcome' 'Autotest training messages. This one has a voice.' '' '' 'DTM_IN_01.wav'
Add-Message $m 'Voiced' 'A second voiced training message.' '' '' 'DTM_IN_02.wav'
Add-Message $m 'Silent' 'A training message with no voice. It stays on screen for its set time.' '' ''
Add-Message $m 'Delayed' 'Queued with a 3 second delay and shown for 6 seconds.' '' '' 'DTM_IN_03.wav'
Add-Message $m 'First of two' 'The first of two messages queued in the same frame.' '' '' 'DTM_IN_04.wav'
Add-Message $m 'Second of two' 'The second of two, which replaces the first.' '' '' 'DTM_IN_05.wav'
Add-Message $m 'Done' 'The last training message.' '' ''

Save-Mission $m
