# AutotestNebFlames: many ships with burning engines at a spread of distances in a full nebula, for
# comparing fogged engine flames, GPU against the CPU renderer. Run with -at_time 60.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestNebFlames' 'Autotest nebula engine flames' @"
Generated by tools/missions/AutotestNebFlames.ps1; edit that, not this file.
Thirty-odd friendly ships circle small squares in a full nebula at 100 m to 3500 m from the player,
fighters, bombers, a freighter, a corvette and a cruiser, seen from every side.
No combat. Run with -at_time 60.
autotest: player stays still
"@
$m.Nebula = $true; $m.NebBack = 'nbackgreen'	# no lightning storm: its flashes whited out the screen for hundreds of frames
$m.Suns = @(@{ Name = 'SunWhite'; Angles = @(0,0,180); Scale = 1 })	# sun behind the player: one ahead whited out the whole screen (sun glare) for hundreds of frames
Add-Player $m @{ Flags = @('cargo-known', 'invulnerable') }

# Name, class, distance (z), x offset, heading (fwd = away, left/right = across, back = toward the player)
$ships = @(
	@('Near 1', 'GTF Myrmidon', 100, 45, 'fwd'),
	@('Near 2', 'GTF Ulysses', 120, -50, 'fwd'),
	@('Near 3', 'GTB Ursa', 160, 70, 'left'),
	@('Near 4', 'SF Mara', 200, -60, 'right'),
	@('Near 5', 'SF Basilisk', 250, 90, 'fwd'),
	@('Mid 1', 'GTF Myrmidon', 300, -110, 'fwd'),
	@('Mid 2', 'SF Aeshma', 400, 80, 'right'),
	@('Mid 3', 'GTB Ursa', 450, -150, 'left'),
	@('Mid 4', 'SB Nephilim', 500, 120, 'fwd'),
	@('Mid 5', 'GTF Ulysses', 550, -40, 'back'),
	@('Mid 6', 'SF Mara', 650, 200, 'left'),
	@('Mid 7', 'GTF Myrmidon', 750, -220, 'fwd'),
	@('Mid 8', 'SF Basilisk', 800, 60, 'right'),
	@('Far 1', 'GTB Ursa', 1000, 300, 'fwd'),
	@('Far 2', 'GTF Ulysses', 1100, -200, 'left'),
	@('Far 3', 'SB Nephilim', 1250, 150, 'back'),
	@('Far 4', 'SF Aeshma', 1400, -350, 'fwd'),
	@('Far 5', 'GTF Myrmidon', 1500, 100, 'right'),
	@('Far 6', 'SF Mara', 1700, -120, 'fwd'),
	@('Far 7', 'GTB Ursa', 2000, 400, 'left'),
	@('Far 8', 'GTF Ulysses', 2300, -300, 'fwd'),
	@('Far 9', 'SF Basilisk', 2600, 250, 'back'),
	@('Far 10', 'GTF Myrmidon', 3000, -400, 'right'),
	@('Far 11', 'SB Nephilim', 3500, 300, 'fwd'),
	@('Big Freighter', 'GTFR Poseidon', 600, -260, 'fwd'),
	@('Big Cruiser', 'GTC Aeolus', 900, 450, 'fwd'),
	@('Big Corvette', 'GTCv Deimos', 1800, -700, 'right'),
	@('Big Cruiser 2', 'GTC Aeolus', 2800, 600, 'left')
)
foreach ($s in $ships) {
	# each ship circles a small square round its start point, so it stays at its distance and shows every side
	$p = @($s[3], 0, $s[2]); $r = [math]::Min(150, 0.4 * $s[2]); $wp = "Path $($s[0])"
	Add-Waypoints $m $wp @(@(($p[0] + $r), 0, $p[2]), @($p[0], 0, ($p[2] + $r)), @(($p[0] - $r), 0, $p[2]), @($p[0], 0, ($p[2] - $r)))
	[void](Add-Ship $m @{ Name = $s[0]; Class = $s[1]; Loc = $p; Face = 'fwd'; Vel = 30
		Goals = "( ai-waypoints `"$wp`" 89 )"; Flags = @('protect-ship', 'invulnerable') })
}

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Message $m 'Start' 'Autotest nebula flames.'
Save-Mission $m
