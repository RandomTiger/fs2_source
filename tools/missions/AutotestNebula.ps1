# AutotestNeb*: a fight in a full nebula, one mission per lightning storm. Run with -at_time 180.
. "$PSScriptRoot\MissionGen.ps1"

foreach ($v in @(@('AutotestNebStandard', 's_standard', 'nbackblue1'), @('AutotestNebActive', 's_active', 'nbackgreen'), @('AutotestNebMedium', 's_medium', 'nbackpurp1'))) {
	$m = New-Mission $v[0] "Autotest nebula $($v[1])" @"
Generated by tools/missions/AutotestNebula.ps1; edit that, not this file.
Autotest test of a full nebula with the $($v[1]) lightning storm: fighters fighting inside and
outside sensor range, an AWACS whose radius changes and whose radar is then destroyed, a cruiser and
a corvette firing beams, bombers, and ships hidden in the nebula. Run with -at_time 180.
"@
	$m.Nebula = $true; $m.Storm = $v[1]; $m.NebBack = $v[2]
	Add-Player $m

	[void](Add-Ship $m @{ Name = 'Charybdis'; Class = 'GTA Charybdis'; Loc = @(-600, 100, -400); Flags = @('escort'); Escort = 30 })
	foreach ($n in 1..4) {
		[void](Add-Ship $m @{ Name = "Beta $n"; Class = 'GTF Myrmidon'; Loc = @((-200 + 100 * $n), 0, -200); Vel = 50; Goals = '( ai-chase-wing "Kappa" 89 )'; Hull = 60 })
		[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Mara'; Team = 'Hostile'; Loc = @((-200 + 100 * $n), 0, (1200 + 600 * $n)); Face = 'back'; Vel = 50
			Goals = '( ai-chase-wing "Beta" 89 )'; Hull = 60 })
	}
	Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2', 'Beta 3', 'Beta 4'); Hotkey = 1 }
	Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3', 'Kappa 4'); Waves = 2; Threshold = 1 }
	[void](Add-Ship $m @{ Name = 'Theta 1'; Class = 'SB Nephilim'; Team = 'Hostile'; Loc = @(800, 300, 3500); Face = 'back'; Vel = 40; Goals = '( ai-chase "Deimos" 89 )' })
	[void](Add-Ship $m @{ Name = 'Theta 2'; Class = 'SB Nephilim'; Team = 'Hostile'; Loc = @(900, 300, 3600); Face = 'back'; Vel = 40; Goals = '( ai-chase "Charybdis" 89 )' })
	Add-Wing $m @{ Name = 'Theta'; Ships = @('Theta 1', 'Theta 2'); ArrCue = '( is-event-true-delay "Bombers" 0 )' }
	[void](Add-Ship $m @{ Name = 'Deimos'; Class = 'GTCv Deimos'; Loc = @(1000, 0, 800); Face = 'left'; Flags = @('escort'); Escort = 20 })
	[void](Add-Ship $m @{ Name = 'Lilith'; Class = 'SC Lilith'; Team = 'Hostile'; Loc = @(1000, 0, 3000); Face = 'back'; Vel = 10; Goals = '( ai-chase "Deimos" 89 )' })

	Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
	Add-Step $m 'Beams' 10 @('( beam-free-all "Deimos" )', '( beam-free-all "Lilith" )', '( turret-free-all "Deimos" )', '( turret-free-all "Lilith" )')
	Add-Step $m 'Short sensors' 10 @('( awacs-set-radius "Charybdis" "radara" 500 )')
	Add-Step $m 'Bombers' 10 @('( send-message "#Command" "High" "Bombers" )')
	Add-Step $m 'Long sensors' 15 @('( awacs-set-radius "Charybdis" "radara" 6000 )')
	Add-Step $m 'Radar down' 20 @('( sabotage-subsystem "Charybdis" "radara" 100 )')
	Add-Step $m 'Cruiser down' 20 @('( self-destruct "Lilith" )')

	Add-Event $m @{ Name = 'Kappa down'; Formula = '( is-destroyed-delay 0 "Kappa" )'; Objective = 'Destroy Kappa' }
	Add-Event $m @{ Name = 'Theta down'; Formula = '( is-destroyed-delay 0 "Theta" )' }
	Add-Goal $m 'Primary' 'Kappa' 'Destroy Kappa' '( is-destroyed-delay 0 "Kappa" )'

	Add-Message $m 'Start' "Autotest nebula, $($v[1]) storm."
	Add-Message $m 'Bombers' 'Shivan bombers in the nebula.'
	Save-Mission $m
	$m = $null
}
