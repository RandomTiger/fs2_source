# VisualSpace: visual reference view, not a test. Open space with nebula and planet bitmaps and a Shivan destroyer's dark side.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'VisualSpace' 'Visual: space' @'
Generated by tools/missions/VisualSpace.ps1; edit that, not this file.
Visual reference view for comparing renderers, not a gated test. The opening view is the shot:
background nebulas and two planets, a Ravana broadside with its unlit side to the camera (glow maps),
a Lilith and an Aeolus nearer in. The sun is high beyond the ships, so they show their dark sides
with lit tops. Everything is still and on one team.
autotest: player stays still
Run with -at_time 60.
'@
$m.Stars = 2000
$m.Suns = @(@{ Name = 'SunWhite'; Angles = @(-50, 0, 10); Scale = 1.5 })
$m.Bitmaps = @(
	@{ Name = 'dneb03'; Angles = @(-5, 0, 15); ScaleX = 4; ScaleY = 4; DivX = 2; DivY = 2 }
	@{ Name = 'neb18'; Angles = @(-15, 30, -25); ScaleX = 3; ScaleY = 2.5 }
	@{ Name = 'planeth'; Angles = @(12, 0, -22); ScaleX = 1.6; ScaleY = 1.6 }
	@{ Name = 'planetc'; Angles = @(-14, 0, 24); ScaleX = 0.4; ScaleY = 0.4 }
)

Add-Player $m
[void](Add-Ship $m @{ Name = 'Ravana'; Class = 'SD Ravana'; Loc = @(0, -750, 3300); Face = 'left' })
[void](Add-Ship $m @{ Name = 'Lilith'; Class = 'SC Lilith'; Loc = @(-330, 110, 800); Face = 'right' })
[void](Add-Ship $m @{ Name = 'Aeolus'; Class = 'GTC Aeolus'; Loc = @(300, 40, 650); Face = 'left' })

Save-Mission $m
