# AudioScenes: the listening scenes for the audio assessment (docs/AUDIO_ASSESSMENT.md on PrePortCleanup),
# one short mission each, AudioA to AudioG. The player sits at the origin facing +z and the scene happens around
# it, so DirectSound and DirectSound3D (Soundcard=EAX) can be heard side by side on the same recording.
. "$PSScriptRoot\MissionGen.ps1"

function New-Scene([string]$Letter, [string]$Title, [string]$What, [int]$Time, [switch]$PlayerFlies) {
	$still = if ($PlayerFlies) { '' } else { "`nautotest: player stays still" }
	$m = New-Mission "Audio$Letter" "Audio scene $Letter`: $Title" @"
Generated by tools/missions/AudioScenes.ps1; edit that, not this file.
Audio assessment scene $Letter`: $What
Run with -at_time $Time$still
"@
	$m
}

# A. Side flyby: pan and doppler.
$m = New-Scene 'A' 'side flyby' 'a fighter passes left to right, 50 m in front of the player.' 30
Add-Player $m
Add-Waypoints $m 'Across' @(@(600, 0, 50), @(2500, 0, 50))
[void](Add-Ship $m @{ Name = 'Beta 1'; Class = 'GTF Myrmidon'; Loc = @(-700, 0, 50); Face = 'right'; Vel = 70
	Goals = '( ai-waypoints-once "Across" 89 )'; Flags = @('protect-ship') })
Save-Mission $m

# B. Overhead flyby: front to back and above, which fake 3D cannot place.
$m = New-Scene 'B' 'overhead flyby' 'a fighter passes from in front to behind, 30 m above the player.' 30
Add-Player $m
Add-Waypoints $m 'Over' @(@(0, 30, -600), @(0, 30, -2500))
[void](Add-Ship $m @{ Name = 'Beta 1'; Class = 'GTF Myrmidon'; Loc = @(0, 30, 700); Face = 'back'; Vel = 70
	Goals = '( ai-waypoints-once "Over" 89 )'; Flags = @('protect-ship') })
Save-Mission $m

# C. Behind: an explosion the player cannot see. Also the scene for #17 (shockwave impacts at full volume).
$m = New-Scene 'C' 'explosion behind' 'a freighter explodes 300 m directly behind the player.' 20
Add-Player $m
[void](Add-Ship $m @{ Name = 'Hauler'; Class = 'GTFR Poseidon'; Loc = @(0, 0, -300); Cargo = 'Nothing' })
Add-Step $m 'Blow' 5 @('( self-destruct "Hauler" )')
Save-Mission $m

# D. Approach: distance falloff from 3 km.
$m = New-Scene 'D' 'approach' 'a bomber flies straight in from 3 km to 100 m, then turns away.' 70
Add-Player $m
Add-Waypoints $m 'Inbound' @(@(0, 0, 100), @(400, 0, 600), @(2500, 0, 2500))
[void](Add-Ship $m @{ Name = 'Gamma 1'; Class = 'GTB Ursa'; Loc = @(0, 0, 3000); Face = 'back'; Vel = 55
	Goals = '( ai-waypoints-once "Inbound" 89 )'; Flags = @('protect-ship') })
Save-Mission $m

# E. Capital ship: engine and turret loops moving past.
$m = New-Scene 'E' 'capital ship' 'a cruiser moves past 150 m to the right, its turrets firing at three fighters.' 60
Add-Player $m
Add-Waypoints $m 'Pass' @(@(150, 0, -800), @(150, 0, -3000))
[void](Add-Ship $m @{ Name = 'Aeolus'; Class = 'GTC Aeolus'; Loc = @(150, 0, 700); Face = 'back'; Vel = 25
	Goals = '( ai-waypoints-once "Pass" 89 )'; Flags = @('protect-ship') })
foreach ($n in 1..3) {
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Basilisk'; Team = 'Hostile'; Loc = @((150 + 120 * $n), 60, 900); Face = 'back'; Vel = 50
		Goals = '( ai-chase "Aeolus" 89 )'; Flags = @('protect-ship') })
}
Add-Step $m 'Turrets' 1 @('( turret-free-all "Aeolus" )')
Save-Mission $m

# F. Crowd: many sounds at once.
$m = New-Scene 'F' 'crowd' 'six fighters a side dogfight around the player.' 40
Add-Player $m
foreach ($n in 1..6) {
	$a = $n * 60 * [Math]::PI / 180
	[void](Add-Ship $m @{ Name = "Beta $n"; Class = 'GTF Myrmidon'; Loc = @([Math]::Round(250 * [Math]::Cos($a)), 0, [Math]::Round(250 * [Math]::Sin($a))); Vel = 50
		Goals = '( ai-chase-any 89 )' })
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Basilisk'; Team = 'Hostile'; Loc = @([Math]::Round(450 * [Math]::Cos($a)), 40, [Math]::Round(450 * [Math]::Sin($a))); Face = 'back'; Vel = 50
		Goals = '( ai-chase-any 89 )' })
}
Save-Mission $m

# G. Control: the player's own guns and engine are not positional, so both backends must sound the same.
$m = New-Scene 'G' 'control' 'the AI flies the player at a container 300 m ahead and fires its guns.' 25 -PlayerFlies
Add-Player $m @{ Goals = '( ai-chase "Target" 89 )'; Flags = @('cargo-known') }
[void](Add-Ship $m @{ Name = 'Target'; Class = 'TC 2'; Team = 'Hostile'; Loc = @(0, 0, 300); Flags = @('protect-ship') })
Save-Mission $m
