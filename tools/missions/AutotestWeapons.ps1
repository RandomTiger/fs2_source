# AutotestWeapons: one fight per weapon type. Run with -at_time 180.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestWeapons' 'Autotest weapons' @'
Generated by tools/missions/AutotestWeapons.ps1; edit that, not this file.
Autotest test of weapons. Pairs of fighters duel with set loadouts: heat seekers, aspect seekers,
dumbfire, swarm and cluster missiles, EMP, energy drain, pushback, anti-subsystem, long range.
Bombers with shockwave bombs attack a cruiser whose turrets shoot the bombs down, Shivan bombers
attack a corvette with flak, a TAG missile marks the cruiser for a tagged-only cruiser, and beams
fire on order and freely. AI countermeasures throughout. Run with -at_time 180.
'@

Add-Player $m

# Duels: friendly loadout against a hostile fighter, spread around the player (some behind).
$duels = @(
	@('Beta 1', 'GTF Myrmidon', @('Subach HL-7', 'Prometheus R'), @('Rockeye', 'Tempest'), 'Kappa 1', 'SF Mara', @(0, 0, 700)),
	@('Beta 2', 'GTF Ares', @('Morning Star', 'Subach HL-7'), @('Harpoon', 'Hornet'), 'Kappa 2', 'SF Basilisk', @(600, 100, 300)),
	@('Beta 3', 'GTF Perseus', @('Maxim', 'Subach HL-7'), @('Tornado', 'Infyrno'), 'Kappa 3', 'SF Dragon', @(-600, -100, 300)),
	@('Beta 4', 'GTF Erinyes', @('Lamprey', 'Circe'), @('EMP Adv.', 'Trebuchet'), 'Kappa 4', 'SF Aeshma', @(0, 200, -700)),
	@('Beta 5', 'GTF Hercules Mark II', @('UD-8 Kayser', 'Akheton SDG'), @('Stiletto II', 'Piranha'), 'Kappa 5', 'SF Manticore', @(500, -150, -500)))
foreach ($d in $duels) {
	$p = $d[6]
	[void](Add-Ship $m @{ Name = $d[0]; Class = $d[1]; Loc = @($p[0], $p[1], ($p[2] - 250)); Vel = 50; Primary = $d[2]; Secondary = $d[3]
		Goals = "( ai-chase `"$($d[4])`" 89 )"; Hull = 100 })
	[void](Add-Ship $m @{ Name = $d[4]; Class = $d[5]; Team = 'Hostile'; Loc = @($p[0], $p[1], ($p[2] + 250)); Face = 'back'; Vel = 50
		Goals = "( ai-chase `"$($d[0])`" 89 )"; Hull = 100 })
}
Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2', 'Beta 3', 'Beta 4', 'Beta 5'); Hotkey = 1 }
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3', 'Kappa 4', 'Kappa 5') }

# Capital ships, arriving later.
[void](Add-Ship $m @{ Name = 'Lilith'; Class = 'SC Lilith'; Team = 'Hostile'; Loc = @(0, 0, 2200); Face = 'back'
	ArrCue = '( is-event-true-delay "Capitals" 0 )'; Score = 100 })
[void](Add-Ship $m @{ Name = 'Aeolus'; Class = 'GTC Aeolus'; Loc = @(-900, 0, 1400); Face = 'right'
	ArrCue = '( is-event-true-delay "Capitals" 0 )'; Flags = @('escort'); Escort = 10; Score = 100 })
[void](Add-Ship $m @{ Name = 'Deimos'; Class = 'GTCv Deimos'; Loc = @(1200, 0, 1200); Face = 'left'
	ArrCue = '( is-event-true-delay "Capitals" 0 )'; Flags = @('escort'); Escort = 20; Score = 100 })

# Bombers with shockwave bombs against the Lilith; Shivan bombers against the Deimos.
[void](Add-Ship $m @{ Name = 'Gamma 1'; Class = 'GTB Ursa'; Loc = @(-200, 0, 200); Vel = 40; Secondary = @('Cyclops', 'Helios')
	Goals = '( ai-chase "Lilith" 89 )' })
[void](Add-Ship $m @{ Name = 'Gamma 2'; Class = 'GTB Ursa'; Loc = @(-260, 0, 180); Vel = 40; Secondary = @('Helios', 'Cyclops')
	Goals = '( ai-chase "Lilith" 89 )' })
Add-Wing $m @{ Name = 'Gamma'; Ships = @('Gamma 1', 'Gamma 2'); ArrCue = '( is-event-true-delay "Bombers" 0 )' }
[void](Add-Ship $m @{ Name = 'Theta 1'; Class = 'SB Nephilim'; Team = 'Hostile'; Loc = @(1500, 200, 2400); Face = 'back'; Vel = 40
	Goals = '( ai-chase "Deimos" 89 )' })
[void](Add-Ship $m @{ Name = 'Theta 2'; Class = 'SB Taurvi'; Team = 'Hostile'; Loc = @(1600, 220, 2420); Face = 'back'; Vel = 40
	Goals = '( ai-chase "Deimos" 89 )' })
Add-Wing $m @{ Name = 'Theta'; Ships = @('Theta 1', 'Theta 2'); ArrCue = '( is-event-true-delay "Bombers" 0 )' }

# TAG: Delta marks the Lilith, then the Aeolus fires only on tagged ships.
[void](Add-Ship $m @{ Name = 'Delta 1'; Class = 'GTF Pegasus'; Loc = @(-400, 50, 800); Vel = 50; Secondary = @('TAG-A', 'TAG-A')
	Goals = '( ai-chase "Lilith" 89 )'; ArrCue = '( is-event-true-delay "Tag" 0 )' })

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'Capitals' 25 @('( send-message "#Command" "High" "Capitals" )')
Add-Step $m 'Turrets' 5 @('( turret-free-all "Lilith" )', '( turret-free-all "Deimos" )')
Add-Step $m 'Bombers' 5 @('( send-message "#Command" "High" "Bombers" )')
Add-Step $m 'Fire beam' 15 @('( fire-beam "Aeolus" "turret11" "Lilith" )', '( fire-beam "Aeolus" "turret12" "Lilith" )')
Add-Step $m 'Tagged only' 10 @('( turret-tagged-only "Aeolus" )', '( beam-free-all "Aeolus" )')
Add-Step $m 'Tag' 2 @('( send-message "#Command" "High" "Tag" )')
Add-Step $m 'Tag clear' 25 @('( turret-tagged-clear "Aeolus" )', '( beam-free-all "Deimos" )', '( beam-free-all "Lilith" )')
Add-Step $m 'Lock' 20 @('( beam-lock-all "Lilith" )', '( turret-lock-all "Deimos" )')
Add-Step $m 'Unlock' 10 @('( turret-free-all "Deimos" )')

Add-Event $m @{ Name = 'Lilith tagged'; Formula = '( has-been-tagged-delay 0 "Lilith" )' }
Add-Event $m @{ Name = 'Kappa down'; Formula = '( is-destroyed-delay 0 "Kappa" )'; Objective = 'Destroy Kappa' }
Add-Event $m @{ Name = 'Lilith down'; Formula = '( is-destroyed-delay 0 "Lilith" )' }
Add-Event $m @{ Name = 'Theta down'; Formula = '( is-destroyed-delay 0 "Theta" )' }

Add-Goal $m 'Primary' 'Kappa' 'Destroy Kappa' '( is-destroyed-delay 0 "Kappa" )'
Add-Goal $m 'Secondary' 'Lilith' 'Destroy the Lilith' '( is-destroyed-delay 0 "Lilith" )'

Add-Message $m 'Start' 'Autotest weapons. Beta, engage.'
Add-Message $m 'Capitals' 'Capital ships arriving.'
Add-Message $m 'Bombers' 'Bombers inbound.'
Add-Message $m 'Tag' 'Delta, tag the Lilith.'

Save-Mission $m
