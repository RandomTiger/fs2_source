# VisualSubspace: visual reference view, not a test. Inside a subspace tunnel with ships alongside.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'VisualSubspace' 'Visual: subspace' @'
Generated by tools/missions/VisualSubspace.ps1; edit that, not this file.
Visual reference view for comparing renderers, not a gated test. The opening view is the shot:
inside subspace, an Aeolus alongside and a Lilith further ahead for glow against the tunnel.
Everything is still and on one team.
autotest: player stays still
Run with -at_time 60.
'@
$m.MissionFlags = 1

Add-Player $m
[void](Add-Ship $m @{ Name = 'Aeolus'; Class = 'GTC Aeolus'; Loc = @(-200, -60, 600) })
[void](Add-Ship $m @{ Name = 'Lilith'; Class = 'SC Lilith'; Loc = @(150, 20, 550) })

Save-Mission $m
