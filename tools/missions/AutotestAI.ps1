# AutotestAI: every AI order a mission can give, on a timeline. Run with -at_time 200.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestAI' 'Autotest AI orders' @'
Generated by tools/missions/AutotestAI.ps1; edit that, not this file.
Autotest test of AI orders. A timeline from the mission start gives, in turn: dock, undock and
carry cargo, guard, guard wing, stay near, keep safe distance, chase, chase wing, chase any,
evade, ignore, disable, disarm, destroy subsystem, waypoints (looping and once), stay still,
play dead, clear goals and warp out. Also wings with two waves, AI classes, and a cruiser fight.
Run with -at_time 200.
'@

Add-Player $m
Add-Waypoints $m 'Patrol' @(@(400, 0, 600), @(400, 0, 1400), @(-400, 0, 1400), @(-400, 0, 600))
Add-Waypoints $m 'Haul' @(@(-300, 0, 1500), @(-1500, 200, 2500))
Add-Waypoints $m 'Run' @(@(800, 100, 1800), @(2500, 300, 3500))

# Freighter docks with a container at the start.
[void](Add-Ship $m @{ Name = 'Poseidon'; Class = 'GTFR Poseidon'; Loc = @(-300, 0, 300); AIClass = 'Lieutenant'
	Goals = '( ai-dock "Container" "cargo dock" "cargo dock" 89 )'; Flags = @('escort'); Escort = 20 })
[void](Add-Ship $m @{ Name = 'Container'; Class = 'TC 2'; Loc = @(-300, 0, 700); Cargo = 'Medical supplies' })
# Transport flying a loop.
[void](Add-Ship $m @{ Name = 'Isis'; Class = 'GVT Isis'; Loc = @(400, 0, 450); Goals = '( ai-waypoints "Patrol" 50 )' })

# Beta: one order each.
$beta = @(
	@('Beta 1', '( ai-guard "Poseidon" 89 )', 'Captain'),
	@('Beta 2', '( ai-stay-near-ship "Isis" 89 )', 'Lieutenant'),
	@('Beta 3', '( ai-keep-safe-distance 89 )', 'Coward'),
	@('Beta 4', '( ai-chase-any 89 )', 'Major'))
$x = -150
foreach ($b in $beta) {
	[void](Add-Ship $m @{ Name = $b[0]; Class = 'GTF Myrmidon'; Loc = @($x, 20, -300); Vel = 50; Goals = $b[1]; AIClass = $b[2] })
	$x += 100
}
Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2', 'Beta 3', 'Beta 4'); Hotkey = 1 }

# Kappa: hostile fighters, two waves, going for Beta.
$x = -200
foreach ($n in 1..4) {
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Basilisk'; Team = 'Hostile'; Loc = @($x, 50, 1800); Face = 'back'; Vel = 60
		Goals = '( ai-chase-wing "Beta" 89 )'; Hull = 60 })
	$x += 130
}
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3', 'Kappa 4'); Waves = 2; Threshold = 1
	ArrCue = '( is-event-true-delay "Hostiles" 0 )' }

# Mephisto runs for the jump; Gamma disables and disarms it, Delta guards Gamma.
[void](Add-Ship $m @{ Name = 'Mephisto'; Class = 'SFr Mephisto'; Team = 'Hostile'; Loc = @(700, 50, 1000); Vel = 20
	Goals = '( ai-waypoints-once "Run" 89 )'; ArrCue = '( is-event-true-delay "Freighter" 0 )' })
[void](Add-Ship $m @{ Name = 'Gamma 1'; Class = 'GTB Ursa'; Loc = @(500, 0, -200); Vel = 40; Goals = '( ai-disable-ship "Mephisto" 89 )' })
[void](Add-Ship $m @{ Name = 'Gamma 2'; Class = 'GTB Ursa'; Loc = @(560, 0, -220); Vel = 40; Goals = '( ai-disarm-ship "Mephisto" 89 )' })
Add-Wing $m @{ Name = 'Gamma'; Ships = @('Gamma 1', 'Gamma 2'); ArrCue = '( is-event-true-delay "Freighter" 0 )' }
[void](Add-Ship $m @{ Name = 'Delta 1'; Class = 'GTF Ulysses'; Loc = @(620, 30, -260); Vel = 50; Goals = '( ai-guard-wing "Gamma" 89 )'
	ArrCue = '( is-event-true-delay "Freighter" 0 )' })

# Cruisers: Aeolus goes for the Lilith's weapons.
[void](Add-Ship $m @{ Name = 'Aeolus'; Class = 'GTC Aeolus'; Loc = @(-800, 0, 1200); Vel = 15
	Goals = '( ai-destroy-subsystem "Lilith" "weapons" 89 )'; ArrCue = '( is-event-true-delay "Cruisers" 0 )'; Flags = @('escort'); Escort = 10 })
[void](Add-Ship $m @{ Name = 'Lilith'; Class = 'SC Lilith'; Team = 'Hostile'; Loc = @(-800, 0, 2400); Face = 'back'; Vel = 15
	Goals = '( ai-chase "Aeolus" 89 )'; ArrCue = '( is-event-true-delay "Cruisers" 0 )' })

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'Hostiles' 5 @('( send-message "#Command" "High" "Hostiles" )')
Add-Step $m 'Evade' 12 @('( add-goal "Beta 3" ( ai-evade-ship "Kappa 1" 89 ) )')
Add-Step $m 'Ignore' 6 @('( add-goal "Kappa" ( ai-ignore "Beta 2" 89 ) )')
Add-Step $m 'Freighter' 6 @('( send-message "#Command" "High" "Freighter" )')
Add-Step $m 'Cruisers' 12 @('( send-message "#Command" "High" "Cruisers" )')
Add-Step $m 'Weapons free' 3 @('( beam-free-all "Aeolus" )', '( turret-free-all "Lilith" )')
Add-Step $m 'Stay still' 10 @('( clear-goals "Isis" )', '( add-goal "Isis" ( ai-stay-still "Isis" 89 ) )')
Add-Step $m 'Play dead' 10 @('( clear-goals "Isis" )', '( add-goal "Isis" ( ai-play-dead 89 ) )')
Add-Step $m 'Regroup' 10 @('( clear-wing-goals "Beta" )', '( add-goal "Beta" ( ai-chase-wing "Kappa" 89 ) )')
Add-Step $m 'Chase' 10 @('( add-goal "Beta 1" ( ai-chase "Mephisto" 89 ) )', '( clear-ship-goals "Isis" )', '( add-goal "Isis" ( ai-waypoints-once "Haul" 89 ) )')
Add-Step $m 'Withdraw' 20 @('( add-goal "Beta" ( ai-warp-out 89 ) )', '( add-goal "Aeolus" ( ai-warp-out 89 ) )', '( add-goal "Delta 1" ( ai-warp-out 89 ) )', '( send-message "#Command" "High" "Withdraw" )')

Add-Event $m @{ Name = 'Docked'; Formula = "( when`n   ( has-docked-delay `"Poseidon`" `"Container`" 1 0 )`n   ( add-goal `"Poseidon`" ( ai-waypoints-once `"Haul`" 89 ) )`n)"; Objective = 'Poseidon docks' }
Add-Event $m @{ Name = 'Undock'; Chained = 20; Formula = "( when`n   ( true )`n   ( add-goal `"Poseidon`" ( ai-undock 89 ) )`n)" }
Add-Event $m @{ Name = 'Undocked'; Formula = "( has-undocked-delay `"Poseidon`" `"Container`" 1 0 )" }
Add-Event $m @{ Name = 'Disabled'; Formula = '( is-disabled-delay 0 "Mephisto" )'; Objective = 'Disable the Mephisto' }
Add-Event $m @{ Name = 'Disarmed'; Formula = '( is-disarmed-delay 0 "Mephisto" )' }
Add-Event $m @{ Name = 'Lilith weapons'; Formula = '( is-subsystem-destroyed-delay "Lilith" "weapons" 0 )' }
Add-Event $m @{ Name = 'Kappa down'; Formula = '( is-destroyed-delay 0 "Kappa" )'; Objective = 'Destroy Kappa' }
Add-Event $m @{ Name = 'Beta gone'; Formula = '( has-departed-delay 0 "Beta" )' }

Add-Goal $m 'Primary' 'Docking' 'Poseidon docks with the container' '( is-event-true-delay "Docked" 0 )'
Add-Goal $m 'Secondary' 'Disable' 'Disable the Mephisto' '( is-disabled-delay 0 "Mephisto" )'
Add-Goal $m 'Bonus' 'Lilith weapons' 'Destroy the Lilith''s weapons' '( is-subsystem-destroyed-delay "Lilith" "weapons" 0 )'

Add-Message $m 'Start' 'Autotest AI orders. Poseidon, dock with the container.'
Add-Message $m 'Hostiles' 'Shivan fighters arriving. Beta, engage.'
Add-Message $m 'Freighter' 'A Shivan freighter is making a run. Gamma, disable it.'
Add-Message $m 'Cruisers' 'Aeolus, take out the Lilith''s weapons.'
Add-Message $m 'Withdraw' 'All ships withdraw.'

Save-Mission $m
