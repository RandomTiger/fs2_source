# AutotestLeaks: the known places where presentation could leak into gameplay, in one short mission (D-031).
# Run with -at_time 150.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestLeaks' 'Autotest presentation leaks' @'
Generated by tools/missions/AutotestLeaks.ps1; edit that, not this file.
Autotest test of the paths where sound or drawing has fed gameplay (decision D-031), flown by the AI:
a voiced message cut short by its speaker's death (message timing and the death scream), looping
sounds across a kill (beams firing at a ship that dies, engine loops of dying ships), EMP missiles
hitting the player, and nebula lightning in an active storm. Run with -at_time 150.
'@
$m.Nebula = $true; $m.Storm = 's_active'; $m.NebBack = 'nbackgreen'

Add-Player $m @{ Goals = '( ai-chase-wing "Kappa" 89 )' }

# the speaker: talks, then dies two seconds into a long voiced message
[void](Add-Ship $m @{ Name = 'Beta 1'; Class = 'GTF Myrmidon'; Loc = @(-150, 0, 100); Vel = 30; Goals = '( ai-guard "Alpha 1" 89 )' })
[void](Add-Ship $m @{ Name = 'Beta 2'; Class = 'GTF Myrmidon'; Loc = @(-50, 0, 100); Vel = 30; Goals = '( ai-guard "Alpha 1" 89 )' })
Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2'); Hotkey = 1 }

# EMP: hostile fighters with EMP missiles on the player, invulnerable until the speakers are done so the fight lasts
foreach ($n in 1..2) {
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Aeshma'; Team = 'Hostile'; Loc = @((-200 + 200 * $n), 50, 900); Face = 'back'; Vel = 50
		Goals = '( ai-chase "Alpha 1" 89 )'; Secondary = @('EMP Adv.', 'EMP Adv.'); Flags = @('invulnerable') })
}
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2') }

# looping sounds across a kill: a cruiser's beams on a cruiser that dies under them
[void](Add-Ship $m @{ Name = 'Deimos'; Class = 'GTCv Deimos'; Loc = @(800, 0, 400); Face = 'left' })
[void](Add-Ship $m @{ Name = 'Lilith'; Class = 'SC Lilith'; Team = 'Hostile'; Loc = @(800, 0, 1600); Face = 'back'; Vel = 5; Hull = 30 })

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'Speaker talks' 8 @('( send-message "Beta 1" "High" "Long message" )')
Add-Step $m 'Speaker dies' 2 @('( self-destruct "Beta 1" )')
Add-Step $m 'Beams' 8 @('( beam-free-all "Deimos" )', '( turret-free-all "Deimos" )')
Add-Step $m 'Cruiser dies' 25 @('( self-destruct "Lilith" )')
Add-Step $m 'Second speaker' 10 @('( send-message "Beta 2" "High" "Long message" )')
Add-Step $m 'Second speaker dies' 3 @('( self-destruct "Beta 2" )')
Add-Step $m 'Kappa vulnerable' 5 @('( ship-vulnerable "Kappa 1" "Kappa 2" )')

Add-Event $m @{ Name = 'Kappa down'; Formula = '( is-destroyed-delay 0 "Kappa" )'; Objective = 'Destroy Kappa' }
Add-Goal $m 'Primary' 'Kappa' 'Destroy Kappa' '( is-destroyed-delay 0 "Kappa" )'

Add-Message $m 'Start' 'Autotest presentation leaks.'
Add-Message $m 'Long message' 'This is a long voiced message, and its speaker will not live to finish it.' 'Head-TP2' '' 'DTM_IN_01.wav'

Save-Mission $m
