# AutotestSquadMenu: autotest works the squadmate messaging menu with key presses. Run with -at_time 70.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestSquadMenu' 'Autotest squad menu' @'
Generated by tools/missions/AutotestSquadMenu.ps1; edit that, not this file.
autotest: squad menu
Autotest test of the squadmate messaging menu (the Communications Menu key, C). Autotest presses the menu keys at fixed
mission times: open the menu, pick Wings, the first wing and an order; open it and cancel; open it and let it time out;
open it and pick All fighters and an order. Beta flies against a few weak Kappa ships meanwhile. Run with -at_time 70.
'@

Add-Player $m
foreach ($n in 1..3) {
	[void](Add-Ship $m @{ Name = "Beta $n"; Class = 'GTF Myrmidon'; Loc = @((-300 + 120 * $n), 0, 200); Vel = 30
		Goals = '( ai-chase-wing "Kappa" 89 )' })
}
Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2', 'Beta 3'); Hotkey = 1 }
foreach ($n in 1..3) {
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Mara'; Team = 'Hostile'; Loc = @((-300 + 150 * $n), 50, 1500); Face = 'back'; Vel = 30; Hull = 20
		Goals = '( ai-chase-wing "Beta" 89 )'; Primary = @('Shivan Light Laser') })
}
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3'); Waves = 2; Threshold = 0 }

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Goal $m 'Primary' 'Kappa' 'Destroy Kappa' '( is-destroyed-delay 0 "Kappa" )'
Add-Message $m 'Start' 'Autotest squad menu. Beta, stand by for orders.'

Save-Mission $m
