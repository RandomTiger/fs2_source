# AutotestHudJitter: HUD jitter from nebula lightning and EMP hits, for the BitmapSections evidence (D-20261029-075126 D).
# A full nebula under the s_emp storm (its bolts carry an EMP and strike near the player), and EMP missiles from
# hostile fighters that the script sends at the player. The player stays still with the HUD shown. Ends itself:
# the player is destroyed at the end. Run with -at_time 150.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestHudJitter' 'Autotest HUD jitter' @'
Generated by tools/missions/AutotestHudJitter.ps1; edit that, not this file.
Autotest test of the HUD under EMP: a full nebula with the s_emp lightning storm (bolts with an EMP that hit
the player's area) and, from the script, two waves of hostile fighters firing EMP missiles at the player. The
HUD is shown the whole time, and the player ends the mission by being destroyed.
autotest: mission controls vulnerability
autotest: player stays still
Run with -at_time 150.
'@
$m.Nebula = $true; $m.Storm = 's_emp'; $m.NebBack = 'nbackpurp2'

Add-Player $m @{ Flags = @('cargo-known', 'invulnerable') }

# a friendly and a scannable freighter to give the HUD targets (the EMP also scrambles the target)
[void](Add-Ship $m @{ Name = 'Deimos'; Class = 'GTCv Deimos'; Loc = @(600, 0, 500); Face = 'left'; Flags = @('escort'); Escort = 20 })
[void](Add-Ship $m @{ Name = 'Freighter'; Class = 'GTFR Poseidon'; Loc = @(-300, 0, 400); Flags = @('scannable', 'cargo-known') })
foreach ($n in 1..2) {
	[void](Add-Ship $m @{ Name = "Beta $n"; Class = 'GTF Myrmidon'; Loc = @((-120 + 240 * $n), 40, 150); Vel = 0; Goals = '( ai-guard "Alpha 1" 89 )' })
}
Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2'); Hotkey = 1 }

# the EMP hits: two waves of hostile fighters with EMP missiles, invulnerable while they shoot
foreach ($w in @(@('Kappa', 25, 'Wave 1'), @('Theta', 55, 'Wave 2'))) {
	foreach ($n in 1..2) {
		[void](Add-Ship $m @{ Name = "$($w[0]) $n"; Class = 'SF Aeshma'; Team = 'Hostile'; Loc = @((-200 + 200 * $n), 50, 900); Face = 'back'; Vel = 50
			Goals = '( ai-chase "Alpha 1" 89 )'; Secondary = @('EMP Adv.', 'EMP Adv.'); Flags = @('invulnerable') })
	}
	Add-Wing $m @{ Name = $w[0]; Ships = @("$($w[0]) 1", "$($w[0]) 2"); ArrCue = "( is-event-true-delay `"$($w[2])`" 0 )" }
}

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'Wave 1' 25 @('( send-message "#Command" "High" "Wave" )')
Add-Step $m 'Kappa out' 25 @('( ship-vulnerable "Kappa 1" "Kappa 2" )', '( self-destruct "Kappa 1" )', '( self-destruct "Kappa 2" )')
Add-Step $m 'Wave 2' 5 @('( send-message "#Command" "High" "Wave" )')
Add-Step $m 'Theta out' 30 @('( ship-vulnerable "Theta 1" "Theta 2" )', '( self-destruct "Theta 1" )', '( self-destruct "Theta 2" )')
Add-Step $m 'Storm only' 20 @('( send-message "#Command" "High" "Storm" )')
Add-Step $m 'End' 15 @('( ship-vulnerable "Alpha 1" )', '( self-destruct "Alpha 1" )')
Add-Goal $m 'Primary' 'Survive' 'Ride out the storm' '( is-event-true-delay "End" 0 )'

Add-Message $m 'Start' 'Autotest HUD jitter.'
Add-Message $m 'Wave' 'Hostile fighters with EMP missiles.'
Add-Message $m 'Storm' 'Storm only.'

Save-Mission $m
