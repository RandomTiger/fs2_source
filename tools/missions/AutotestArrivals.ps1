# AutotestArrivals: every way to arrive and depart, waves, delays, jump node. Run with -at_time 200.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestArrivals' 'Autotest arrivals' @'
Generated by tools/missions/AutotestArrivals.ps1; edit that, not this file.
Autotest test of arrivals and departures. Wings launch from a friendly destroyer's fighter bay and
a Shivan destroyer's bays, arrive near a ship and in front of a ship, with delays and several waves.
They depart to the bays, to hyperspace on a timer, through a jump node, and to a bay that has been
destroyed (they then warp out). Run with -at_time 200.
'@

Add-Player $m
$m.JumpNodes.Add(@{ Name = 'Node'; Loc = @(2500, 0, 2500) }) | Out-Null
Add-Waypoints $m 'To node' @(@(1500, 100, 1800), @(2450, 0, 2450))

[void](Add-Ship $m @{ Name = 'Carrier'; Class = 'GTD Hecate'; Loc = @(-1500, 0, 1500); Face = 'right'; Score = 200 })
[void](Add-Ship $m @{ Name = 'Demon'; Class = 'SD Demon'; Team = 'Hostile'; Loc = @(1500, 0, 5000); Face = 'left'; Score = 200 })

function Add-Fighters([string]$Wing, [string]$Class, [string]$Team, [int]$Count, $Loc, [string]$Goals) {
	$names = @()
	foreach ($n in 1..$Count) {
		$name = "$Wing $n"
		[void](Add-Ship $m @{ Name = $name; Class = $Class; Team = $Team; Loc = @(($Loc[0] + 60 * $n), $Loc[1], $Loc[2]); Vel = 50; Goals = $Goals; Hull = 50 })
		$names += $name
	}
	, $names
}

# Beta: launches from the Hecate, two waves, back to the bay on order.
$s = Add-Fighters 'Beta' 'GTF Myrmidon' 'Friendly' 3 @(-1500, 0, 1500) '( ai-chase-wing "Kappa" 89 )'
Add-Wing $m @{ Name = 'Beta'; Ships = $s; Waves = 2; Threshold = 1; Arr = 'Docking Bay'; ArrAnchor = 'Carrier'
	ArrCue = '( is-event-true-delay "Launch" 0 )'; Dep = 'Docking Bay'; DepAnchor = 'Carrier'; DepCue = '( is-event-true-delay "Return" 0 )'; Hotkey = 1 }
# Kappa: launches from the Demon, three waves, back to the Demon on order.
$s = Add-Fighters 'Kappa' 'SF Mara' 'Hostile' 3 @(1500, 0, 5000) '( ai-chase-wing "Beta" 89 )'
Add-Wing $m @{ Name = 'Kappa'; Ships = $s; Waves = 3; Threshold = 1; Arr = 'Docking Bay'; ArrAnchor = 'Demon'
	ArrCue = '( is-event-true-delay "Launch" 0 )'; Dep = 'Docking Bay'; DepAnchor = 'Demon'; DepCue = '( is-event-true-delay "Return" 0 )' }
# Gamma: arrives near the player after a delay, leaves by hyperspace on a timer.
$s = Add-Fighters 'Gamma' 'GTF Ulysses' 'Friendly' 2 @(0, 0, 0) '( ai-chase-wing "Kappa" 89 )'
Add-Wing $m @{ Name = 'Gamma'; Ships = $s; Arr = 'Near Ship'; ArrDist = 800; ArrAnchor = 'Alpha 1'; ArrDelay = 5
	ArrCue = '( is-event-true-delay "Escorts" 0 )'; DepCue = '( has-time-elapsed 120 )'; DepDelay = 3 }
# Delta: arrives in front of the Hecate; later told to land in its destroyed bay.
$s = Add-Fighters 'Delta' 'GTB Ursa' 'Friendly' 2 @(0, 0, 0) '( ai-chase "Demon" 89 )'
Add-Wing $m @{ Name = 'Delta'; Ships = $s; Arr = 'In front of ship'; ArrDist = 1000; ArrAnchor = 'Carrier'
	ArrCue = '( is-event-true-delay "Escorts" 0 )'; Dep = 'Docking Bay'; DepAnchor = 'Carrier'; DepCue = '( is-event-true-delay "Bay gone" 0 )' }
# Single ships: one with an arrival delay, one leaving through the jump node.
[void](Add-Ship $m @{ Name = 'Courier'; Class = 'GVT Isis'; Loc = @(500, 200, 800); Vel = 30; ArrDelay = 8
	ArrCue = '( is-event-true-delay "Escorts" 0 )'; Goals = '( ai-waypoints-once "To node" 89 )'
	DepCue = '( are-waypoints-done-delay "Courier" "To node" 0 )' })
[void](Add-Ship $m @{ Name = 'Freighter'; Class = 'GTFR Poseidon'; Loc = @(-300, -100, 400); Vel = 20
	DepCue = '( is-event-true-delay "Freighter leaves" 0 )'; DepDelay = 4 })

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'Launch' 3 @('( send-message "#Command" "High" "Launch" )')
Add-Step $m 'Escorts' 15 @('( send-message "#Command" "High" "Escorts" )')
Add-Step $m 'Freighter leaves' 15 @('( send-message "#Command" "High" "Freighter" )')
Add-Step $m 'Return' 30 @('( send-message "#Command" "High" "Return" )')
Add-Step $m 'Bay gone' 20 @('( sabotage-subsystem "Carrier" "fighterbay" 100 )', '( send-message "#Command" "High" "Bay" )')
Add-Step $m 'Withdraw' 30 @('( add-goal "Carrier" ( ai-warp-out 89 ) )', '( add-goal "Demon" ( ai-warp-out 89 ) )')

Add-Event $m @{ Name = 'Courier node'; Formula = '( depart-node-delay 0 "Node" "Courier" )' }
Add-Event $m @{ Name = 'Beta home'; Formula = '( has-departed-delay 0 "Beta" )' }
Add-Event $m @{ Name = 'Kappa home'; Formula = '( destroyed-or-departed-delay 0 "Kappa" )' }
Add-Event $m @{ Name = 'Delta gone'; Formula = '( has-departed-delay 0 "Delta" )' }
Add-Event $m @{ Name = 'Gamma gone'; Formula = '( has-departed-delay 0 "Gamma" )' }
Add-Event $m @{ Name = 'Carrier gone'; Formula = '( has-departed-delay 0 "Carrier" )' }

Add-Goal $m 'Primary' 'Courier' 'The courier leaves through the jump node' '( depart-node-delay 0 "Node" "Courier" )'

Add-Message $m 'Start' 'Autotest arrivals and departures.'
Add-Message $m 'Launch' 'Launch fighters.'
Add-Message $m 'Escorts' 'Escorts arriving.'
Add-Message $m 'Freighter' 'Freighter, you may leave.'
Add-Message $m 'Return' 'All fighters return to base.'
Add-Message $m 'Bay' 'The Hecate''s fighter bay is gone. Delta, land anyway.'

Save-Mission $m
