# VisualMovingParts: visual reference view, not a test. Every ship class whose model has a continuously rotating part.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'VisualMovingParts' 'Visual: ships with moving parts' @'
Generated by tools/missions/VisualMovingParts.ps1; edit that, not this file.
Visual reference view for the 3D ship renderer, not a gated test. One of every ship class that has a part
turning on its own ($rotate subsystems: radar dishes, solar panels, grinders, claws, jump-node rings, comm
node pieces), laid out on an arc in front of the camera, broadside on, still, one team. Big ships stand
further out. Turret-only classes are not here: they only move when they aim at a target.
autotest: player stays still
Run with -at_time 60 -at_speed 1.
'@
$m.Stars = 2000
$m.Suns = @(@{ Name = 'SunWhite'; Angles = @(-30, 20, 0); Scale = 1.2 })

Add-Player $m

# Class, distance from the camera (m, a guess from the ship's size: adjust after looking), moving part.
$ships = @(
	@('GTI Ganymede', 350, 'hoses, pieces'),
	@('GVG Anuket', 600, 'claw'),
	@('GTSC Faustus', 700, 'solar panel'),
	@('GVT Isis', 700, 'landing gear'),
	@('GVFr Bes', 800, 'clamps'),
	@('SFr Asmodeus', 900, 'clamps'),
	@('GTM Hippocrates', 1000, 'radar dish'),
	@('SSG Rahu', 1300, 'back piece'),
	@('GTSG Mjolnir', 1500, 'grinders'),
	@('GTI Arcadia', 1600, 'radar dish'),
	@('GTC Fenris', 1800, 'radar dish'),
	@('GTC Leviathan', 2200, 'radar dish'),
	@('GTA Charybdis', 2600, 'radar dish'),
	@('GVA Setekh', 2800, 'radar dish'),
	@('GTD Orion', 3000, 'radar dishes x3'),
	@('GTD Orion#2 (Bastion)', 3200, 'radar dishes x3'),
	@('Shivan Comm Node', 3400, 'five pieces'),
	@('Knossos', 3800, 'jump rings'),
	@('GTVA Colossus', 6500, 'radar dishes x6'))

$n = $ships.Count
for ($i = 0; $i -lt $n; $i++) {
	$a = (-55 + 110 * $i / ($n - 1)) * [math]::PI / 180
	$r = $ships[$i][1]
	[void](Add-Ship $m @{ Name = 'MP ' + ($i + 1); Class = $ships[$i][0]; Loc = @([math]::Round($r * [math]::Sin($a)), 0, [math]::Round($r * [math]::Cos($a))); Face = 'left' })
}

Save-Mission $m
