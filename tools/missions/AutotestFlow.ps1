# AutotestFlow: mission logic itself - repeating events, variables, goals that fail and are
# invalidated, message queues, directives, cargo, IFF and escort changes. Run with -at_time 180.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestFlow' 'Autotest mission flow' @'
Generated by tools/missions/AutotestFlow.ps1; edit that, not this file.
Autotest test of mission logic: repeating events with intervals, variables, cond, and-in-sequence,
goals that succeed, fail, and are invalidated and validated again, directives that complete and
fail, many messages queued at once at different priorities, random messages and message lists,
wingman deaths (builtin messages), cargo transfer, exchange and jettison, IFF and escort list
changes, and comparisons on hull, shields, distance and time. Run with -at_time 180.
'@
[void]$m.Variables.Add(@{ Name = 'count'; Value = '0'; Type = 'number' })
[void]$m.Variables.Add(@{ Name = 'phase'; Value = '0'; Type = 'number' })

Add-Player $m
foreach ($n in 1..4) {
	[void](Add-Ship $m @{ Name = "Beta $n"; Class = 'GTF Myrmidon'; Loc = @((-200 + 100 * $n), 0, 300); Vel = 40; Goals = '( ai-chase-wing "Kappa" 89 )'; Hull = 50 })
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Mara'; Team = 'Hostile'; Loc = @((-200 + 100 * $n), 0, 1500); Face = 'back'; Vel = 40
		Goals = '( ai-chase-wing "Beta" 89 )'; Hull = 50 })
}
Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2', 'Beta 3', 'Beta 4'); Hotkey = 1 }
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3', 'Kappa 4'); ArrCue = '( is-event-true-delay "Hostiles" 0 )' }
[void](Add-Ship $m @{ Name = 'Poseidon'; Class = 'GTFR Poseidon'; Loc = @(-500, 0, 600); Cargo = 'Fuel'; Flags = @('escort'); Escort = 5 })
[void](Add-Ship $m @{ Name = 'Container'; Class = 'TC 2'; Loc = @(-500, 0, 900); Cargo = 'Food'; Docked = @('Poseidon', 'cargo dock', 'cargo dock') })
[void](Add-Ship $m @{ Name = 'Isis'; Class = 'GVT Isis'; Loc = @(500, 0, 600); Cargo = 'Medicine' })
[void](Add-Ship $m @{ Name = 'Doomed'; Class = 'GTFR Poseidon'; Loc = @(600, 200, 1200); Team = 'Neutral' })

# Repeating counter: five times, every 3 seconds.
Add-Event $m @{ Name = 'Counter'; Repeat = 5; Interval = 3
	Formula = "( when`n   ( true )`n   ( modify-variable @count[0] ( + @count[0] 1 ) )`n)" }
Add-Event $m @{ Name = 'Counted'; Formula = '( = @count[0] 5 )'; Objective = 'Count to five' }

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'Hostiles' 3 @('( send-message "Beta 1" "Normal" "Engaging" )')
Add-Step $m 'Flood' 8 @('( send-message "#Command" "Low" "Low 1" )', '( send-message "#Command" "Low" "Low 2" )', '( send-message "Beta 2" "Normal" "Normal 1" )', '( send-message "Beta 3" "Normal" "Normal 2" )', '( send-message "#Command" "High" "High 1" )', '( send-message "#Command" "High" "High 2" )', '( send-random-message "#Command" "Normal" "Low 1" "Low 2" "Normal 1" )')
Add-Step $m 'List' 4 @('( send-message-list "#Command" "High" "List 1" 0 "Beta 1" "Normal" "List 2" 3000 "#Command" "Low" "List 3" 2000 )')
Add-Step $m 'Cargo' 8 @('( transfer-cargo "Container" "Poseidon" )', '( exchange-cargo "Poseidon" "Container" )', '( cargo-no-deplete "Poseidon" )')
Add-Step $m 'Jettison' 5 @('( jettison-cargo-delay "Poseidon" 0 )')
Add-Step $m 'Invalidate' 5 @('( invalidate-goal "Doomed survives" )', '( add-remove-escort "Isis" 15 )', '( add-remove-escort "Poseidon" 0 )')
Add-Step $m 'Doom' 5 @('( self-destruct "Doomed" )', '( modify-variable @phase[0] 1 )')
Add-Step $m 'Validate' 5 @('( validate-goal "Doomed survives" )')
Add-Step $m 'Losses' 5 @('( self-destruct "Beta 4" )')
Add-Step $m 'Defect' 10 @('( change-iff "Hostile" "Beta 3" )', '( add-goal "Beta 3" ( ai-chase "Beta 1" 89 ) )', '( send-message "#Command" "High" "Defect" )')
Add-Step $m 'Training' 5 @('( training-msg "Training" )')
Add-Step $m 'Branch' 5 @('( cond ( ( = @phase[0] 1 ) ( modify-variable @phase[0] 2 ) ( send-message "#Command" "Normal" "Phase two" ) ) ( ( true ) ( send-message "#Command" "Normal" "Phase none" ) ) )')

Add-Event $m @{ Name = 'Sequence'; Formula = '( and-in-sequence ( is-event-true-delay "Cargo" 0 ) ( is-event-true-delay "Doom" 0 ) )' }
Add-Event $m @{ Name = 'Doomed alive'; Formula = '( not ( is-destroyed-delay 0 "Doomed" ) )'; Objective = 'Keep the Doomed alive' }
Add-Event $m @{ Name = 'Late'; Formula = '( and ( has-time-elapsed 60 ) ( > ( hits-left "Isis" ) 50 ) ( < ( distance "Alpha 1" "Isis" ) 2000 ) ( not ( < ( shields-left "Isis" ) 0 ) ) )' }
Add-Event $m @{ Name = 'Fighters lost'; Formula = '( percent-ships-destroyed 25 "Beta 1" "Beta 2" "Beta 3" "Beta 4" )' }
Add-Event $m @{ Name = 'Freighter killed'; Formula = '( ship-type-destroyed 1 "freighter" )' }
Add-Event $m @{ Name = 'Cargo known'; Formula = '( is-cargo-known-delay 0 "Isis" )' }

Add-Goal $m 'Primary' 'Count' 'Count to five' '( is-event-true-delay "Counted" 0 )'
Add-Goal $m 'Primary' 'Doomed survives' 'The Doomed survives' '( not ( is-destroyed-delay 0 "Doomed" ) )'
Add-Goal $m 'Secondary' 'Kappa' 'Destroy Kappa' '( is-destroyed-delay 0 "Kappa" )'
Add-Goal $m 'Bonus' 'Sequence' 'Events in sequence' '( is-event-true-delay "Sequence" 0 )'

Add-Message $m 'Start' 'Autotest mission flow.'
Add-Message $m 'Engaging' 'Beta engaging.' 'Head-TP1' ''
foreach ($n in 'Low 1', 'Low 2', 'High 1', 'High 2', 'List 1', 'List 3', 'Phase two', 'Phase none', 'Defect') { Add-Message $m $n "Message $n." }
foreach ($n in 'Normal 1', 'Normal 2', 'List 2') { Add-Message $m $n "Wingman message $n." 'Head-TP2' '' }
Add-Message $m 'Training' 'A training message.' '' ''

Save-Mission $m
