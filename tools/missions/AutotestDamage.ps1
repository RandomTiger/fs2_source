# AutotestDamage: subsystem damage, break-up in and out of view, guardian, collisions. Run with -at_time 180.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestDamage' 'Autotest damage' @'
Generated by tools/missions/AutotestDamage.ps1; edit that, not this file.
Autotest test of damage and collisions. Subsystems sabotaged, repaired and set at random (engines
stop a ship), damage arcs on ships that start damaged, a guardian ship that cannot die, protected
ships, fighters' death rolls, a docked pair destroyed together, capital ships breaking up in front
of the player and behind, ships vanishing and hidden from radar, two cruisers colliding head-on,
kamikaze fighters ramming a destroyer, and a cruiser flying through an asteroid field.
Run with -at_time 180.
'@

Add-Player $m
$m.Asteroids = @{ Density = 60; Type = 0; Min = @(-3000, -500, 2500); Max = @(-1500, 500, 4000) }
Add-Waypoints $m 'North' @(@(200, -200, 3000), @(200, -200, -3000))
Add-Waypoints $m 'South' @(@(200, -200, -1500), @(200, -200, 3000))
Add-Waypoints $m 'Rocks' @(@(-2200, 0, 3200), @(-2200, 0, 5000))
Add-Waypoints $m 'Loop' @(@(-400, 100, 500), @(-400, 100, -500), @(-900, 100, 0))

# Subsystem victim, flying a loop.
[void](Add-Ship $m @{ Name = 'Victim'; Class = 'GTFR Poseidon'; Loc = @(-400, 100, 500); Vel = 30; Goals = '( ai-waypoints "Loop" 89 )' })
# Ships that start damaged show damage arcs.
[void](Add-Ship $m @{ Name = 'Faustus'; Class = 'GTSC Faustus'; Loc = @(400, 0, 600); Hull = 25 })
# A docked pair destroyed together.
[void](Add-Ship $m @{ Name = 'Poseidon'; Class = 'GTFR Poseidon'; Loc = @(700, -100, 1400); Hull = 50 })
[void](Add-Ship $m @{ Name = 'Container'; Class = 'TC 2'; Loc = @(700, -100, 1700); Cargo = 'Fuel'
	Docked = @('Poseidon', 'cargo dock', 'cargo dock') })
# Guardian cruiser under attack.
[void](Add-Ship $m @{ Name = 'Guard'; Class = 'GTC Aeolus'; Loc = @(-1000, 0, 1500); Face = 'right'; Hull = 30; Flags = @('escort'); Escort = 10 })
[void](Add-Ship $m @{ Name = 'Theta 1'; Class = 'SB Nephilim'; Team = 'Hostile'; Loc = @(-1000, 300, 2400); Face = 'back'; Vel = 40; Goals = '( ai-chase "Guard" 89 )' })
[void](Add-Ship $m @{ Name = 'Theta 2'; Class = 'SB Nephilim'; Team = 'Hostile'; Loc = @(-900, 320, 2420); Face = 'back'; Vel = 40; Goals = '( ai-chase "Guard" 89 )' })
Add-Wing $m @{ Name = 'Theta'; Ships = @('Theta 1', 'Theta 2') }
# Fighters near the player that die in a death roll; one hidden from radar.
foreach ($n in 1..3) {
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Mara'; Team = 'Hostile'; Loc = @((-200 + 150 * $n), 30, 400); Face = 'back'; Vel = 40
		Goals = '( ai-chase "Faustus" 89 )' })
}
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3') }
[void](Add-Ship $m @{ Name = 'Isis'; Class = 'GVT Isis'; Loc = @(300, 200, 300) })
# Capital ships that break up: one in front, one behind.
[void](Add-Ship $m @{ Name = 'Orion'; Class = 'GTD Orion'; Loc = @(0, 0, 3500); Face = 'right'; Score = 200 })
[void](Add-Ship $m @{ Name = 'Demon'; Class = 'SD Demon'; Team = 'Hostile'; Loc = @(0, 0, -3500); Score = 200 })
# Kamikaze fighters ram the Orion.
foreach ($n in 1..2) {
	[void](Add-Ship $m @{ Name = "Iota $n"; Class = 'SF Dragon'; Team = 'Hostile'; Loc = @((-300 + 600 * ($n - 1)), 200, 2000); Vel = 60
		Goals = '( ai-chase "Orion" 89 )'; Flags = @('kamikaze'); Kamikaze = 500 })
}
Add-Wing $m @{ Name = 'Iota'; Ships = @('Iota 1', 'Iota 2'); ArrCue = '( is-event-true-delay "Kamikaze" 0 )' }
# Two cruisers on a head-on course, and one through the asteroids.
[void](Add-Ship $m @{ Name = 'Leviathan'; Class = 'GTC Leviathan'; Loc = @(200, -200, 2600); Face = 'back'; Vel = 30; Goals = '( ai-waypoints-once "North" 89 )' })
[void](Add-Ship $m @{ Name = 'Rakshasa'; Class = 'SC Rakshasa'; Team = 'Hostile'; Loc = @(200, -200, -1000); Vel = 30; Goals = '( ai-waypoints-once "South" 89 )' })
[void](Add-Ship $m @{ Name = 'Miner'; Class = 'SC Lilith'; Team = 'Hostile'; Loc = @(-2200, 0, 2000); Vel = 30; Goals = '( ai-waypoints-once "Rocks" 89 )' })

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( ship-guardian `"Guard`" )`n   ( protect-ship `"Victim`" )`n   ( turret-free-all `"Guard`" )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'Sabotage' 5 @('( sabotage-subsystem "Victim" "engine" 100 )', '( sabotage-subsystem "Victim" "sensors" 100 )', '( set-subsystem-strength "Victim" "weapons" 0 )', '( sabotage-subsystem "Victim" "communication" 60 )', '( sabotage-subsystem "Victim" "navigation" 60 )')
Add-Step $m 'Repair' 12 @('( repair-subsystem "Victim" "engine" 100 )', '( repair-subsystem "Victim" "sensors" 50 )')
Add-Step $m 'Random' 5 @('( subsys-set-random "Faustus" 10 60 )')
Add-Step $m 'Death roll' 5 @('( self-destruct "Kappa 1" "Kappa 2" )')
Add-Step $m 'Hide' 5 @('( ship-invisible "Kappa 3" )', '( ship-vanish "Isis" )')
Add-Step $m 'Kamikaze' 3 @('( send-message "#Command" "High" "Kamikaze" )')
Add-Step $m 'Docked pair' 10 @('( self-destruct "Poseidon" )')
Add-Step $m 'Show' 5 @('( ship-visible "Kappa 3" )')
Add-Step $m 'Break up front' 8 @('( self-destruct "Orion" )', '( send-message "#Command" "High" "Orion" )')
Add-Step $m 'Break up behind' 12 @('( self-destruct "Demon" )')
Add-Step $m 'Unguard' 15 @('( ship-no-guardian "Guard" )', '( unprotect-ship "Victim" )')
Add-Step $m 'Faustus' 10 @('( self-destruct "Faustus" "Kappa 3" )')

Add-Event $m @{ Name = 'Engine down'; Formula = '( is-subsystem-destroyed-delay "Victim" "engine" 0 )' }
Add-Event $m @{ Name = 'Victim disabled'; Formula = '( is-disabled-delay 0 "Victim" )' }
Add-Event $m @{ Name = 'Guard alive'; Formula = '( and ( is-event-true-delay "Unguard" 0 ) ( not ( is-destroyed-delay 0 "Guard" ) ) )' }
Add-Event $m @{ Name = 'Guard down'; Formula = '( is-destroyed-delay 0 "Guard" )' }
Add-Event $m @{ Name = 'Collision'; Formula = '( < ( distance "Leviathan" "Rakshasa" ) 300 )' }
Add-Event $m @{ Name = 'Iota down'; Formula = '( is-destroyed-delay 0 "Iota" )' }

Add-Goal $m 'Primary' 'Orion' 'The Orion breaks up' '( is-destroyed-delay 0 "Orion" )'
Add-Goal $m 'Primary' 'Demon' 'The Demon breaks up' '( is-destroyed-delay 0 "Demon" )'

Add-Message $m 'Start' 'Autotest damage.'
Add-Message $m 'Kamikaze' 'Kamikaze fighters going for the Orion.'
Add-Message $m 'Orion' 'The Orion is breaking up.'

Save-Mission $m
