# AutotestSupport: AI wingmen call the support ship to repair and rearm. Run with -at_time 240.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestSupport' 'Autotest support ship' @'
Generated by tools/missions/AutotestSupport.ps1; edit that, not this file.
Autotest test of the support ship. Support is allowed; wingmen with damaged subsystems, and others
that fire off their missiles at a few weak targets, call for repair and rearm. The support ship warps
in, docks with each in turn, repairs and rearms them, and leaves. Run with -at_time 240.
'@
$m.Support = $true

Add-Player $m
foreach ($n in 1..4) {
	[void](Add-Ship $m @{ Name = "Beta $n"; Class = 'GTF Myrmidon'; Loc = @((-300 + 120 * $n), 0, 200); Vel = 30; Secondary = @('Harpoon', 'Rockeye')
		Goals = '( ai-chase-wing "Kappa" 89 )' })
}
Add-Wing $m @{ Name = 'Beta'; Ships = @('Beta 1', 'Beta 2', 'Beta 3', 'Beta 4'); Hotkey = 1 }
foreach ($n in 1..4) {
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Mara'; Team = 'Hostile'; Loc = @((-300 + 150 * $n), 50, 1200); Face = 'back'; Vel = 30; Hull = 20
		Goals = '( ai-chase-wing "Beta" 89 )'; Primary = @('Shivan Light Laser') })
}
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3', 'Kappa 4'); Waves = 2; Threshold = 0 }

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( sabotage-subsystem `"Beta 1`" `"engine`" 80 )`n   ( sabotage-subsystem `"Beta 2`" `"weapons`" 90 )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'More damage' 60 @('( sabotage-subsystem "Beta 3" "sensors" 90 )', '( sabotage-subsystem "Beta 4" "communications" 90 )')

Add-Event $m @{ Name = 'Kappa down'; Formula = '( is-destroyed-delay 0 "Kappa" )'; Objective = 'Destroy Kappa' }
Add-Event $m @{ Name = 'Engine fixed'; Formula = '( > ( hits-left-subsystem "Beta 1" "engine" ) 90 )' }
Add-Event $m @{ Name = 'Weapons fixed'; Formula = '( > ( hits-left-subsystem "Beta 2" "weapons" ) 90 )' }
Add-Goal $m 'Primary' 'Kappa' 'Destroy Kappa' '( is-destroyed-delay 0 "Kappa" )'

Add-Message $m 'Start' 'Autotest support ship. Beta, call for support when you need it.'

Save-Mission $m
