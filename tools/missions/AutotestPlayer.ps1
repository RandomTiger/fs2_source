# AutotestPlayer: the player ship in combat, flown by the AI. Run with -playernpc -at_time 240.
. "$PSScriptRoot\MissionGen.ps1"

$m = New-Mission 'AutotestPlayer' 'Autotest player' @'
Generated by tools/missions/AutotestPlayer.ps1; edit that, not this file.
Autotest test of the player ship, for -playernpc (the AI flies the player). The player fights
fighters with missiles, takes damage and calls the support ship, attacks a cruiser through its
flak, guards a freighter, flies waypoints, and is finally destroyed, which ends the mission. A
guardian keeps the player alive until then. Without -playernpc nobody flies the player.
autotest: mission controls vulnerability
Run with -playernpc -at_time 240.
'@
$m.Support = $true

Add-Waypoints $m 'Patrol' @(@(0, 0, 1500), @(1000, 200, 1500), @(1000, 200, 0))
Add-Player $m @{ Goals = '( ai-chase-wing "Kappa" 89 )'; Primary = @('Subach HL-7', 'Prometheus R'); Secondary = @('Harpoon', 'Rockeye') }

foreach ($n in 1..4) {
	[void](Add-Ship $m @{ Name = "Kappa $n"; Class = 'SF Basilisk'; Team = 'Hostile'; Loc = @((-300 + 150 * $n), 50, 1500); Face = 'back'; Vel = 40; Hull = 60
		Goals = '( ai-chase "Alpha 1" 89 )' })
}
Add-Wing $m @{ Name = 'Kappa'; Ships = @('Kappa 1', 'Kappa 2', 'Kappa 3', 'Kappa 4'); Waves = 2; Threshold = 1 }
[void](Add-Ship $m @{ Name = 'Freighter'; Class = 'GTFR Poseidon'; Loc = @(-600, 0, 400); Vel = 15; Goals = '( ai-waypoints "Patrol" 50 )' })
[void](Add-Ship $m @{ Name = 'Theta 1'; Class = 'SB Nephilim'; Team = 'Hostile'; Loc = @(-600, 300, 2500); Face = 'back'; Vel = 40
	Goals = '( ai-chase "Freighter" 89 )'; ArrCue = '( is-event-true-delay "Guard" 0 )' })
[void](Add-Ship $m @{ Name = 'Buoy'; Class = 'TC 2'; Loc = @(0, -300, 0); Cargo = 'Nothing' })
[void](Add-Ship $m @{ Name = 'Lilith'; Class = 'SC Lilith'; Team = 'Hostile'; Loc = @(800, 0, 2500); Face = 'back'; Hull = 40
	ArrCue = '( is-event-true-delay "Cruiser" 0 )' })

Add-Event $m @{ Name = 'Start'; Formula = "( when`n   ( true )`n   ( ship-guardian `"Alpha 1`" )`n   ( ship-vulnerable `"Alpha 1`" )`n   ( send-message `"#Command`" `"High`" `"Start`" )`n)" }
Add-Step $m 'Damage' 30 @('( sabotage-subsystem "Alpha 1" "engines" 70 )', '( sabotage-subsystem "Alpha 1" "weapons" 60 )')
Add-Step $m 'Cruiser' 40 @('( clear-goals "Alpha 1" )', '( add-goal "Alpha 1" ( ai-chase "Lilith" 89 ) )', '( send-message "#Command" "High" "Cruiser" )')
Add-Step $m 'Flak' 5 @('( turret-free-all "Lilith" )')
Add-Step $m 'Guard' 40 @('( clear-goals "Alpha 1" )', '( add-goal "Alpha 1" ( ai-guard "Freighter" 89 ) )', '( send-message "#Command" "High" "Guard" )')
Add-Step $m 'Patrol' 40 @('( clear-goals "Alpha 1" )', '( add-goal "Alpha 1" ( ai-waypoints-once "Patrol" 89 ) )')
Add-Step $m 'End' 30 @('( ship-no-guardian "Alpha 1" )', '( self-destruct "Alpha 1" )')

Add-Event $m @{ Name = 'Kappa down'; Formula = '( is-destroyed-delay 0 "Kappa" )'; Objective = 'Destroy Kappa' }
Add-Event $m @{ Name = 'Player moved'; Formula = '( > ( distance "Alpha 1" "Buoy" ) 800 )' }
Add-Event $m @{ Name = 'Player hurt'; Formula = '( < ( hits-left "Alpha 1" ) 80 )' }
Add-Event $m @{ Name = 'Engine fixed'; Formula = '( and ( is-event-true-delay "Damage" 1 ) ( > ( hits-left-subsystem "Alpha 1" "engines" ) 90 ) )' }
Add-Event $m @{ Name = 'Lilith down'; Formula = '( is-destroyed-delay 0 "Lilith" )' }
Add-Goal $m 'Primary' 'Kappa' 'Destroy Kappa' '( is-destroyed-delay 0 "Kappa" )'
Add-Goal $m 'Secondary' 'Lilith' 'Destroy the Lilith' '( is-destroyed-delay 0 "Lilith" )'

Add-Message $m 'Start' 'Autotest player. Alpha 1, engage.'
Add-Message $m 'Cruiser' 'Alpha 1, attack the cruiser.'
Add-Message $m 'Guard' 'Alpha 1, protect the freighter.'

Save-Mission $m
